"""محاسبهٔ دقیق ابجد کبیر و پیدا کردن نزدیک‌ترین اسماءالحسنی، تا جمع زدن به عهدهٔ مدل نباشد."""

import re

ABJAD = {
    "ا": 1, "ب": 2, "ج": 3, "د": 4, "ه": 5, "و": 6, "ز": 7, "ح": 8, "ط": 9,
    "ی": 10, "ک": 20, "ل": 30, "م": 40, "ن": 50, "س": 60, "ع": 70, "ف": 80,
    "ص": 90, "ق": 100, "ر": 200, "ش": 300, "ت": 400, "ث": 500, "خ": 600,
    "ذ": 700, "ض": 800, "ظ": 900, "غ": 1000,
}
# حروف فارسی و شکل‌های دیگر هر حرف، به حرف معادل ابجدی
EQUIVALENT = {
    "پ": "ب", "چ": "ج", "ژ": "ز", "گ": "ک", "ك": "ک", "ي": "ی", "ى": "ی",
    "ئ": "ی", "ؤ": "و", "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ة": "ه", "ۀ": "ه",
}

# اسماءالحسنی بدون «ال»؛ برای «الله» عدد سنتی ۶۶ ملاک است
ASMA = [
    "الله", "رحمن", "رحیم", "ملک", "قدوس", "سلام", "مؤمن", "مهیمن", "عزیز", "جبار",
    "متکبر", "خالق", "بارئ", "مصور", "غفار", "قهار", "وهاب", "رزاق", "فتاح", "علیم",
    "قابض", "باسط", "خافض", "رافع", "معز", "مذل", "سمیع", "بصیر", "حکم", "عدل",
    "لطیف", "خبیر", "حلیم", "عظیم", "غفور", "شکور", "علی", "کبیر", "حفیظ", "مقیت",
    "حسیب", "جلیل", "کریم", "رقیب", "مجیب", "واسع", "حکیم", "ودود", "مجید", "باعث",
    "شهید", "حق", "وکیل", "قوی", "متین", "ولی", "حمید", "محصی", "مبدئ", "معید",
    "محیی", "ممیت", "حی", "قیوم", "واجد", "ماجد", "واحد", "احد", "صمد", "قادر",
    "مقتدر", "مقدم", "مؤخر", "اول", "آخر", "ظاهر", "باطن", "والی", "متعالی", "بر",
    "تواب", "منتقم", "عفو", "رئوف", "مالک الملک", "ذو الجلال و الاکرام", "مقسط",
    "جامع", "غنی", "مغنی", "مانع", "ضار", "نافع", "نور", "هادی", "بدیع", "باقی",
    "وارث", "رشید", "صبور",
]
FIXED_VALUES = {"الله": 66}


def abjad(text: str) -> int:
    """جمع ابجد کبیر همهٔ حروف؛ فاصله، اعراب، تشدید و هر علامت دیگری نادیده گرفته می‌شود."""
    return sum(ABJAD.get(EQUIVALENT.get(ch, ch), 0) for ch in text)


def divine_value(name: str) -> int:
    if name in FIXED_VALUES:
        return FIXED_VALUES[name]
    # «ال» ابتدای هر کلمه در اسم الهی حساب نمی‌شود
    return abjad(" ".join(w[2:] if w.startswith("ال") else w for w in name.split()))


ASMA_VALUES = {name: divine_value(name) for name in ASMA}


def date_digit_sum(date: str) -> int:
    """جمع همهٔ ارقام تاریخ (روز، ماه و سال)؛ ارقام فارسی و عربی هم پذیرفته می‌شوند."""
    date = date.translate(str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789"))
    return sum(int(d) for d in re.findall(r"\d", date))


def nearest_names(number: int, count: int = 8) -> list[dict]:
    ranked = sorted(ASMA_VALUES.items(), key=lambda kv: (abs(kv[1] - number), kv[1]))
    return [
        {"name": n, "abjad": v, "distance": abs(v - number)} for n, v in ranked[:count]
    ]


def calculate(full_name: str, mother_name: str, birth_date: str) -> dict:
    numbers = {
        "zekr_1": abjad(full_name),
        "zekr_2": abjad(full_name) + abjad(mother_name),
        "zekr_3": date_digit_sum(birth_date),
    }
    return {
        key: {"number": n, "nearest_asma": nearest_names(n)} for key, n in numbers.items()
    }
